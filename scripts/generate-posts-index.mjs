#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const POSTS_DIR = path.join(ROOT, 'content', 'posts');
const OUT_FILE = path.join(ROOT, 'src', 'lib', 'posts-content.generated.ts');

function toIdentifier(slug) {
  return (
    'post_' +
    slug.replace(/[^a-zA-Z0-9]+/g, '_').replace(/^_+|_+$/g, '') || 'post'
  );
}

const files = fs.existsSync(POSTS_DIR)
  ? fs.readdirSync(POSTS_DIR).filter((f) => f.endsWith('.mdx'))
  : [];

files.sort();

const imports = files
  .map((f) => {
    const slug = f.replace(/\.mdx$/, '');
    return `import ${toIdentifier(slug)} from '../../content/posts/${f}';`;
  })
  .join('\n');

const entries = files
  .map((f) => {
    const slug = f.replace(/\.mdx$/, '');
    return `  '${slug}': ${toIdentifier(slug)},`;
  })
  .join('\n');

const body = `// AUTO-GENERATED by scripts/generate-posts-index.mjs — do not edit.
${imports}

export const postSources: Record<string, string> = {
${entries}
};
`;

fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });

if (fs.existsSync(OUT_FILE) && fs.readFileSync(OUT_FILE, 'utf8') === body) {
  process.exit(0);
}

fs.writeFileSync(OUT_FILE, body);
console.log(`[posts] wrote ${path.relative(ROOT, OUT_FILE)} (${files.length} posts)`);
